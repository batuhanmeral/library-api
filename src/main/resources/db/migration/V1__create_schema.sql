-- Initial schema. Written for PostgreSQL; the tests run it on H2, so it uses only
-- SQL that both understand. Constraint names are explicit: they show up in
-- error logs (GlobalExceptionHandler logs the name of a violated constraint).

create table categories (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    description varchar(500),
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    created_by  varchar(100) not null,
    updated_by  varchar(100) not null,
    constraint uk_categories_name unique (name)
);

create table authors (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null,
    biography  varchar(4000),
    birth_date date,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    created_by varchar(100) not null,
    updated_by varchar(100) not null
);

create table books (
    id               bigint generated by default as identity primary key,
    isbn             varchar(13),
    title            varchar(255) not null,
    description      varchar(2000),
    published_year   integer,
    page_count       integer,
    total_copies     integer not null,
    available_copies integer not null,
    author_id        bigint not null,
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null,
    created_by       varchar(100) not null,
    updated_by       varchar(100) not null,
    constraint uk_books_isbn unique (isbn),
    constraint fk_books_author foreign key (author_id) references authors (id),
    constraint ck_books_copies check (available_copies >= 0 and available_copies <= total_copies)
);

-- Foreign key columns get no index automatically in PostgreSQL. These are used by
-- "books of an author", "is this author used" and joins.
create index ix_books_author_id on books (author_id);

create table book_categories (
    book_id     bigint not null,
    category_id bigint not null,
    constraint pk_book_categories primary key (book_id, category_id),
    constraint fk_book_categories_book foreign key (book_id) references books (id),
    constraint fk_book_categories_category foreign key (category_id) references categories (id)
);

-- The primary key (book_id, category_id) already serves lookups by book_id.
create index ix_book_categories_category_id on book_categories (category_id);

create table users (
    id         bigint generated by default as identity primary key,
    email      varchar(254) not null,
    password   varchar(100) not null,
    full_name  varchar(200) not null,
    phone      varchar(20),
    role       varchar(20) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_users_email unique (email),
    constraint ck_users_role check (role in ('ADMIN', 'MEMBER'))
);

create table loans (
    id          bigint generated by default as identity primary key,
    book_id     bigint not null,
    member_id   bigint not null,
    loan_date   date not null,
    due_date    date not null,
    return_date date,
    status      varchar(20) not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    created_by  varchar(100) not null,
    updated_by  varchar(100) not null,
    constraint fk_loans_book foreign key (book_id) references books (id),
    constraint fk_loans_member foreign key (member_id) references users (id),
    constraint ck_loans_status check (status in ('ACTIVE', 'OVERDUE', 'RETURNED')),
    constraint ck_loans_dates check (due_date >= loan_date)
);

create index ix_loans_book_id on loans (book_id);
create index ix_loans_member_id on loans (member_id);
